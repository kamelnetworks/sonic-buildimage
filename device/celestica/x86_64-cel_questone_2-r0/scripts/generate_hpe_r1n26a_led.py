#!/usr/bin/env python3
"""Reproduce the R1N26A LED image without changing the stock SDK instructions.

The stock Questone_2A image has the HPE board's serial LED output layout.
Translate its final lane table by matching Ethernet name and lane ordinal
against the Questone_2 physical port map. No assembler or external package
is required. Pinned hashes make a changed input fail for explicit review.
"""

import argparse
import hashlib
from pathlib import Path


SOURCE_SHA256 = "0ac3231e3cb2f05cb78e7715b6a940193eaced4dcece3a2e3d74984578ba46c9"
OUTPUT_SHA256 = "6af4180b7f4a8bda9833a0536b1dd6a00bfac7cd055e225fbdadeb28398ea73b"
TABLE_OFFSET = 228
PORT_ORDER = [f"Ethernet{i}" for i in range(48)] + [
    f"Ethernet{i}" for i in (64, 68, 72, 76, 48, 52, 56, 60)
]


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_lanes(path):
    ports = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split()
        if not fields or fields[0].startswith("#"):
            continue
        name = fields[0]
        require(name not in ports, f"Duplicate port {name} in {path}")
        ports[name] = [int(lane) for lane in fields[1].split(",")]
    require(set(ports) == set(PORT_ORDER), f"Unexpected port set in {path}")
    return ports


def generate(platform):
    original = (platform / "Questone_2A/custom_led.bin").read_bytes()
    require(len(original) == 308, "Unexpected source LED image size")
    require(hashlib.sha256(original).hexdigest() == SOURCE_SHA256,
            "Source LED image changed; review its instructions and table")
    old_ports = read_lanes(platform / "Questone_2A/port_config.ini")
    new_ports = read_lanes(platform / "Questone_2/port_config.ini")
    translation = {}
    for name in PORT_ORDER:
        require(len(old_ports[name]) == len(new_ports[name]), f"Lane count changed for {name}")
        for before, after in zip(old_ports[name], new_ports[name]):
            require(before not in translation, f"Duplicate source lane {before}")
            translation[before] = after
    source_table = bytes(lane for name in PORT_ORDER for lane in old_ports[name])
    require(len(source_table) == 80 and len(set(source_table)) == 80, "Invalid source lane table")
    require(original[TABLE_OFFSET:] == source_table, "Source table order changed")
    target_table = bytes(translation[lane] for lane in source_table)
    require(len(set(target_table)) == 80, "Duplicate target lane")
    result = original[:TABLE_OFFSET] + target_table
    require(hashlib.sha256(result).hexdigest() == OUTPUT_SHA256,
            "Generated mapping changed; review before changing the expected hash")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the committed binary without writing")
    parser.add_argument("--output", type=Path, help="override the output file")
    args = parser.parse_args()
    platform = Path(__file__).resolve().parent.parent
    destination = args.output or platform / "Questone_2/custom_led_hpe_r1n26a.bin"
    result = generate(platform)
    if args.check:
        require(destination.read_bytes() == result, "Committed LED image differs from generated bytes")
    else:
        destination.write_bytes(result)
    print(f"{OUTPUT_SHA256}  {destination}")


if __name__ == "__main__":
    main()
